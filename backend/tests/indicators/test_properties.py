"""Deterministic property tests: truncation invariance, no influence from future bars, repeatability, scaling and
session resets. The series is generated by a fixed formula (no randomness) and includes gaps, zero-volume bars and
a session whose opening range is incomplete."""

import dataclasses
import math
from datetime import date

import pytest

from app.indicators import (
    ADX,
    ATR,
    EMA,
    RSI,
    SMA,
    Bollinger,
    IndicatorBar,
    OpeningRange,
    RollingStd,
    SessionVWAP,
    Supertrend,
    TrueRange,
    WilderAverage,
    run,
)
from tests.indicators import bar

SESSIONS = [date(2026, 11, 2), date(2026, 11, 3), date(2026, 11, 4)]
MISSING = {(0, 40), (1, 1), (2, 73), (2, 74)}  # (session index, slot): a mid-session gap, an opening-range gap, a closing gap


def series(scale: float = 1.0) -> list[IndicatorBar]:
    out = []
    for s, day in enumerate(SESSIONS):
        for slot in range(75):
            if (s, slot) in MISSING:
                continue
            i = s * 75 + slot
            o = 100 + 3 * math.sin(i / 9) + 0.02 * i
            c = o + 0.4 * math.sin(i / 4)
            h = max(o, c) + 0.3 + 0.1 * abs(math.sin(i))
            low = min(o, c) - 0.3 - 0.1 * abs(math.cos(i))
            volume = 0 if slot == 0 else 1000 + (i * 37) % 500
            out.append(bar(day, slot, o * scale, h * scale, low * scale, c * scale, volume))
    return out


BARS = series()
CLOSES = [b.close for b in BARS]

# (name, factory, input kind)
INDICATORS = [
    ("SMA", lambda: SMA(5), "close"),
    ("EMA", lambda: EMA(9), "close"),
    ("RollingStd", lambda: RollingStd(20), "close"),
    ("Wilder", lambda: WilderAverage(14), "close"),
    ("RSI", lambda: RSI(14), "close"),
    ("Bollinger", lambda: Bollinger(20, 2.0), "close"),
    ("TrueRange", TrueRange, "bar"),
    ("ATR", lambda: ATR(14), "bar"),
    ("ADX", lambda: ADX(14), "bar"),
    ("Supertrend", lambda: Supertrend(10, 3.0), "bar"),
    ("SessionVWAP", SessionVWAP, "bar"),
    ("OpeningRange", lambda: OpeningRange(15), "bar"),
]
IDS = [name for name, *_ in INDICATORS]


def inputs(kind, bars):
    return [b.close for b in bars] if kind == "close" else list(bars)


def test_the_series_exercises_gaps_zero_volume_and_an_incomplete_opening_range():
    assert len(BARS) == 3 * 75 - len(MISSING)
    statuses = {b.session_date: v.status.value for b, v in zip(BARS, run(OpeningRange(15), BARS)) if v.status.value != "FORMING"}
    assert statuses == {SESSIONS[0]: "COMPLETE", SESSIONS[1]: "INCOMPLETE", SESSIONS[2]: "COMPLETE"}
    assert sum(1 for b in BARS if b.volume == 0) == 3


@pytest.mark.parametrize("name,make,kind", INDICATORS, ids=IDS)
def test_truncation_invariance(name, make, kind):
    """The output at t is the same whether the data ends at t or continues: no future bar is ever used."""
    xs = inputs(kind, BARS)
    full = run(make(), xs)
    for t in range(len(xs)):
        assert run(make(), xs[: t + 1]) == full[: t + 1], f"{name} differs at t={t}"


@pytest.mark.parametrize("name,make,kind", INDICATORS, ids=IDS)
def test_changing_future_bars_never_changes_earlier_outputs(name, make, kind):
    cut = 100
    perturbed = BARS[:cut] + [dataclasses.replace(b, high=b.high * 1.5, close=b.high * 1.4, volume=b.volume * 7) for b in BARS[cut:]]
    a, b = run(make(), inputs(kind, BARS)), run(make(), inputs(kind, perturbed))
    assert a[:cut] == b[:cut] and a[cut:] != b[cut:]


@pytest.mark.parametrize("name,make,kind", INDICATORS, ids=IDS)
def test_repeatability_is_exact(name, make, kind):
    assert run(make(), inputs(kind, BARS)) == run(make(), inputs(kind, BARS))


def _fields(value):
    return dataclasses.asdict(value) if dataclasses.is_dataclass(value) else value


def test_scaling_prices_by_two_is_exact():
    """Multiplying every price by 2 is exact in float64, so linear indicators scale exactly and ratio indicators
    (RSI, DI, DX, ADX, Supertrend direction) are bit-for-bit unchanged."""
    doubled = series(2.0)
    linear = {"SMA", "EMA", "RollingStd", "Wilder", "Bollinger", "TrueRange", "ATR", "SessionVWAP"}
    for name, make, kind in INDICATORS:
        base, scaled = run(make(), inputs(kind, BARS)), run(make(), inputs(kind, doubled))
        for x, y in zip(base, scaled):
            if x is None:
                assert y is None, name
            elif name in linear:
                fx, fy = _fields(x), _fields(y)
                assert (fy == 2 * fx) if isinstance(fx, float) else all(fy[k] == 2 * fx[k] for k in fx), name
            elif name == "RSI":
                assert x == y
            elif name == "ADX":
                assert (x.plus_di, x.minus_di, x.dx, x.adx) == (y.plus_di, y.minus_di, y.dx, y.adx)
            elif name == "Supertrend":
                assert (y.direction, y.flipped, y.upper, y.lower, y.line) == (x.direction, x.flipped, 2 * x.upper, 2 * x.lower, 2 * x.line)
            elif name == "OpeningRange":
                assert y.status is x.status and (x.high is None or (y.high, y.low) == (2 * x.high, 2 * x.low))


def test_scaling_by_three_preserves_ratios_within_rounding():
    tripled = series(3.0)
    rsi_a, rsi_b = run(RSI(14), CLOSES), run(RSI(14), [b.close for b in tripled])
    adx_a, adx_b = run(ADX(14), BARS), run(ADX(14), tripled)
    assert all(a == pytest.approx(b, rel=1e-9, abs=1e-9) for a, b in zip(rsi_a, rsi_b) if a is not None)
    assert all(a.adx == pytest.approx(b.adx, rel=1e-9, abs=1e-9) for a, b in zip(adx_a, adx_b) if a is not None and a.adx is not None)
    st_a, st_b = run(Supertrend(10, 3.0), BARS), run(Supertrend(10, 3.0), tripled)
    assert [v.direction for v in st_a if v] == [v.direction for v in st_b if v]


@pytest.mark.parametrize("make", [SessionVWAP, lambda: OpeningRange(15)], ids=["SessionVWAP", "OpeningRange"])
def test_session_indicators_reset_at_each_session(make):
    full = run(make(), BARS)
    for day in SESSIONS:
        idx = [i for i, b in enumerate(BARS) if b.session_date == day]
        alone = run(make(), [BARS[i] for i in idx])
        assert [full[i] for i in idx] == alone, day


def test_continuous_indicators_do_not_reset_at_sessions():
    """EMA/RSI/ATR/ADX/Supertrend run across sessions: running a later session alone gives different values."""
    day2 = [b for b in BARS if b.session_date == SESSIONS[1]]
    assert run(EMA(9), [b.close for b in BARS])[-len(day2) - 75 + 2 :][:1] != run(EMA(9), [b.close for b in day2])[:1]
    full_atr = run(ATR(14), BARS)
    start = BARS.index(day2[0])
    assert full_atr[start] is not None and run(ATR(14), day2)[0] is None
